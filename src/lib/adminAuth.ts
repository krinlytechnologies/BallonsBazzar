import { createHmac, randomBytes, scryptSync, timingSafeEqual } from "crypto";

const SESSION_COOKIE = "admin_session";
const SESSION_TTL_MS = 12 * 60 * 60 * 1000; // 12 hours

function getSessionSecret(): string | undefined {
  return process.env.ADMIN_SESSION_SECRET;
}

/**
 * True only when every env var required for admin auth to function is
 * present. Both the login route and the upload-signing route treat
 * "not configured" as "feature disabled", never as "open".
 */
export function isAdminAuthConfigured(): boolean {
  return Boolean(
    process.env.ADMIN_USERNAME &&
      process.env.ADMIN_PASSWORD_HASH &&
      getSessionSecret(),
  );
}

/** Format: `<salt-hex>:<hash-hex>`, generated by `npm run admin:hash-password`. */
export function hashPassword(password: string): string {
  const salt = randomBytes(16).toString("hex");
  const hash = scryptSync(password, salt, 64).toString("hex");
  return `${salt}:${hash}`;
}

export function verifyPassword(password: string, stored: string): boolean {
  const [salt, hash] = stored.split(":");
  if (!salt || !hash) return false;
  const candidate = scryptSync(password, salt, 64);
  const expected = Buffer.from(hash, "hex");
  if (candidate.length !== expected.length) return false;
  return timingSafeEqual(candidate, expected);
}

function sign(value: string, secret: string): string {
  return createHmac("sha256", secret).update(value).digest("base64url");
}

export function createSessionCookieValue(username: string): string {
  const secret = getSessionSecret();
  if (!secret) throw new Error("ADMIN_SESSION_SECRET is not configured.");
  const expires = Date.now() + SESSION_TTL_MS;
  const payload = `${username}.${expires}`;
  return `${payload}.${sign(payload, secret)}`;
}

export function verifySessionCookieValue(value: string | undefined | null): boolean {
  const secret = getSessionSecret();
  if (!secret || !value) return false;

  // Parsed from the right: the username may contain dots, while the expiry and base64url signature never do.
  const signatureDot = value.lastIndexOf(".");
  const expiresDot = value.lastIndexOf(".", signatureDot - 1);
  if (signatureDot === -1 || expiresDot === -1) return false;

  const payload = value.slice(0, signatureDot);
  const signature = value.slice(signatureDot + 1);
  const username = value.slice(0, expiresDot);
  const expiresStr = value.slice(expiresDot + 1, signatureDot);
  if (!username || !expiresStr || !signature) return false;

  const expires = Number(expiresStr);
  if (!Number.isFinite(expires) || Date.now() > expires) return false;

  const expectedSignature = sign(payload, secret);
  const a = Buffer.from(signature);
  const b = Buffer.from(expectedSignature);
  if (a.length !== b.length) return false;
  return timingSafeEqual(a, b);
}

export const ADMIN_SESSION_COOKIE = SESSION_COOKIE;
export const ADMIN_SESSION_MAX_AGE_SECONDS = Math.floor(SESSION_TTL_MS / 1000);
